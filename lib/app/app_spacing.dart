/// Spacing scale based on the 4/8 dp rhythm.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;

  /// Horizontal page padding used on compact devices.
  static const double pagePadding = lg;

  /// Horizontal page padding used on tablet/expanded layouts.
  static const double pagePaddingTablet = xxl;
}
